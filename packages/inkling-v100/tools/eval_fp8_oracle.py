def rms_norm_f32(x: torch.Tensor, w: torch.Tensor | None, eps: float) -> torch.Tensor:
    xf = x.float()
    rstd = torch.rsqrt(xf.square().mean(dim=-1, keepdim=True) + eps)
    y = xf * rstd
    if w is not None:
        y = y * w.float()
    return y


def l2_clip_f32(x: torch.Tensor, threshold: float, eps: float) -> torch.Tensor:
    norm = x.square().sum(dim=-1, keepdim=True).sqrt()
    scale = (threshold / (norm + eps)).clamp_max(1.0)
    return x * scale


def attn_res_f32(
    stack: torch.Tensor,  # [N_stack, T, H]
    last: torch.Tensor,  # [T, H]
    addend: torch.Tensor | None,
    queries: torch.Tensor,  # [Q, H] (pre-scaled by H^-0.5)
    norm_weight: torch.Tensor | None,  # [Q, H] or None
    norm_eps: float,
    normalize_values: bool = True,
    eps: float = 1e-6,
) -> torch.Tensor:
    last_eff = last if addend is None else (last + addend)
    srcs = torch.cat([stack, last_eff.unsqueeze(0)], dim=0)  # [N+1, T, H]
    rstd = torch.rsqrt(srcs.square().mean(dim=-1, keepdim=True) + eps)  # [N+1, T, 1]
    normed = srcs * rstd  # [N+1, T, H]
    # logits: [Q, N+1, T]
    logits = torch.einsum("qh,nth->qnt", queries, normed)
    probs = torch.softmax(logits, dim=1)  # [Q, N+1, T]
    if normalize_values:
        # Matches ops/attn_res.py: probs * inv_rms applied to raw srcs = probs @ normed
        mixed = torch.einsum("qnt,nth->qth", probs, normed)
    else:
        mixed = torch.einsum("qnt,nth->qth", probs, srcs)
    if norm_weight is not None:
        out_rstd = torch.rsqrt(mixed.square().mean(dim=-1, keepdim=True) + norm_eps)
        mixed = mixed * out_rstd * norm_weight.float().unsqueeze(1)
    return mixed


def static_sconv_f32(x: torch.Tensor, w: torch.Tensor) -> torch.Tensor:
    """Causal depthwise conv matching ops/sconv.py static branch:
    x: [T, C], w: [C, 1, W] -> y[t] = (x[t] + sum_{k=0..W-1} w[:, k] * x[t-(W-1-k)]) * (W+1)^-0.5.
    """
    T, C = x.shape
    w2 = w.squeeze(1).float()  # [C, W]
    W = w2.shape[1]
    xf = x.float()
    acc = torch.zeros_like(xf)
    for k in range(W):
        lag = W - 1 - k
        if lag == 0:
            acc = acc + xf * w2[:, k]
        elif lag < T:
            acc[lag:] = acc[lag:] + xf[:-lag] * w2[:, k]
    return (acc + xf) * ((W + 1) ** -0.5)


def dynamic_sconv_f32(
    x: torch.Tensor, static_w: torch.Tensor, dyn: torch.Tensor, head_dim: int
) -> torch.Tensor:
    """Causal dynamic depthwise conv matching ops/sconv.py dynamic branch:
    x: [T, H*D], static_w: [W, H*D], dyn: [T, H*W] -> lag = 0..W-1.
    """
    T, C = x.shape
    W = static_w.shape[0]
    H_kv = C // head_dim
    xf = x.float()
    sw = static_w.float()  # [W, C]
    df = dyn.float().view(T, H_kv, W)  # [T, H_kv, W]
    acc = torch.zeros_like(xf)
    for lag in range(W):
        # Expand dyn[:, :, lag] across head_dim
        w_eff = sw[lag].unsqueeze(0) + df[:, :, lag].repeat_interleave(head_dim, dim=1)
        if lag == 0:
            acc = acc + xf * w_eff
        elif lag < T:
            acc[lag:] = acc[lag:] + xf[:-lag] * w_eff[lag:]
    return (acc + xf) * ((W + 1) ** -0.5)


def dequant_nvfp4_expert(
    w_u8: torch.Tensor, s_f8: torch.Tensor, g_scalar: float
) -> torch.Tensor:
    """Exact NVFP4 expert dequant: [N, K/2] u8 + [N, K/16] f8_e4m3fn + float -> [N, K] f32."""
    N, K2 = w_u8.shape
    lo = E2M1_LUT[(w_u8 & 0x0F).long()]
    hi = E2M1_LUT[((w_u8 >> 4) & 0x0F).long()]
    vals = torch.stack([lo, hi], dim=-1).view(N, K2 * 2)  # [N, K]
    scales = s_f8.float().repeat_interleave(16, dim=1)  # [N, K]
    return vals * scales * g_scalar


def dequant_mxfp8_expert(w_f8: torch.Tensor, s_u8: torch.Tensor) -> torch.Tensor:
    """Exact MXFP8 expert dequant: [N, K] f8_e4m3fn + [N, K/32] u8 UE8M0 -> [N, K] f32."""
    # UE8M0: 2^(e - 127)
    exp = torch.pow(2.0, s_u8.float() - 127.0)
    scales = exp.repeat_interleave(32, dim=1)
    return w_f8.float() * scales


def fp8_roundtrip_weight(w_q: torch.Tensor, s32: torch.Tensor) -> torch.Tensor:
    """Exact QPN8 dequant weight: fp16(code * 2^-8 * fp16(scale * 256)) -> match Volta QPN8!"""
    s16 = (s32.float() * 256.0).half().float()
    return (w_q.float() * (1.0 / 256.0) * s16[:, None]).half()


class WeightStore:
    def __init__(
        self,
        fp8_path: Path | None,
        active_tiers: set[str],
        dense_dtype: torch.dtype,
        model_dir: Path | None = None,
    ):
        mdir = model_dir if model_dir is not None else MODEL_DIR
        self.sf = safe_open(mdir / "model-00001-of-00001.safetensors", framework="pt", device="cpu")
        self.fp8_sf = safe_open(fp8_path, framework="pt", device="cpu") if fp8_path else None
        self.fp8_keys = set(self.fp8_sf.keys()) if self.fp8_sf else set()
        self.active_tiers = active_tiers
        self.dense_dtype = dense_dtype  # float32 (oracle) or float16 (sm_70 runtime)

    def _tier(self, key: str) -> str | None:
        if key == "model.llm.unembed.weight":
            return "lm_head"
        if ".attn." in key and key.endswith(".weight"):
            leaf = key.rsplit(".", 2)[-2]
            if leaf in {"wq_du", "wr_du", "gate_attn", "attn_sink_proj", "wk_dv", "wv_dv", "wo_ud"}:
                return "attn"
        if ".controllers." in key and key.endswith(("_weight",)):
            return "controllers"
        return None

    def get(self, key: str, dtype: torch.dtype | None = None) -> torch.Tensor:
        tier = self._tier(key)
        if self.fp8_sf is not None and tier in self.active_tiers and key in self.fp8_keys:
            w_q = self.fp8_sf.get_tensor(key).to(DEVICE)
            s32 = self.fp8_sf.get_tensor(f"{key}_scale").to(DEVICE)
            # Exact QPN8 math: E4M3FN code * fp16(scale * 256) / 256
            w_eff = fp8_roundtrip_weight(w_q, s32)
            return w_eff.to(dtype or self.dense_dtype)
        t = self.sf.get_tensor(key).to(DEVICE)
        if dtype is not None:
            return t.to(dtype)
        if t.dtype == torch.bfloat16:
            return t.to(self.dense_dtype)
        return t


@torch.no_grad()
def run_forward(
    input_ids_list: list[torch.Tensor],
    cfg: dict,
    ws: WeightStore,
    fp8_kv: bool,
    fp16_compute: bool,
) -> list[torch.Tensor]:
    """Run exact 48-visit Inkling-2-Mini forward on each prompt independently (clean causal KV)."""
    H = cfg["hidden_size"]
    num_layers = cfg["num_hidden_layers"]
    local_ids = set(cfg["local_layer_ids"])
    core_start = cfg["loop_config"]["core_start"]
    core_end = cfg["loop_config"]["core_end"]
    num_passes = cfg["loop_config"]["num_passes"]
    block_size = cfg["n_layers_per_attn_res_block"]
    eps = cfg["rms_norm_eps"]
    n_heads = cfg["num_attention_heads"]
    n_kv = cfg["num_key_value_heads"]
    hd = cfg["head_dim"]
    d_rel = cfg["d_rel"]
    rel_extent = cfg["rel_extent"]
    sw = cfg["sliding_window_size"]
    qk_clip = cfg["qk_l2_clip_threshold"]
    rel_clip = cfg["rel_l2_clip_threshold"]
    gate_cap = cfg["mlp_gate_softcap"]
    up_cap = cfg["mlp_up_softcap"]
    route_scale = cfg["route_scale"]
    topk = cfg["num_experts_per_tok"]
    softcap = cfg["final_logit_softcapping"]
    unpadded_vocab = cfg["unpadded_vocab_size"]

    # Preload small global query tables
    inv_sqrt_h = H ** -0.5
    attn_queries = [
        ws.get(f"model.llm.attn_res.attn_queries.{i}", torch.float32).view(-1, H) * inv_sqrt_h
        for i in range(num_layers - 1)
    ]
    mlp_queries = [
        ws.get(f"model.llm.attn_res.mlp_queries.{i}", torch.float32).view(1, H) * inv_sqrt_h
        for i in range(num_layers)
    ]
    output_query = ws.get("model.llm.attn_res.output_query", torch.float32).view(1, H) * inv_sqrt_h
    q_cp = ws.get("model.llm.middle_cycle_cross_pass_queries", torch.float32).view(-1, 2, H)
    kv_cp = ws.get("model.llm.middle_cycle_cross_pass_kv_queries", torch.float32).view(-1, 2, H)
    msg_queries = torch.stack((q_cp[:, 0], kv_cp[:, 0], kv_cp[:, 1], q_cp[:, 1]), dim=1) * inv_sqrt_h

    embed_w = ws.get("model.llm.embed.weight")
    embed_norm_w = ws.get("model.llm.embed_norm.weight")
    final_norm_w = ws.get("model.llm.norm.weight")

    # Initialize per-prompt state so we only load each physical layer from disk ONCE per pass!
    B = len(input_ids_list)
    states = []
    for ids in input_ids_list:
        T = ids.numel()
        pos = torch.arange(T, device=DEVICE, dtype=torch.float32)
        tau = 1.0 + cfg["log_scaling_alpha"] * torch.log(((pos + 1.0) / cfg["log_scaling_n_floor"]).clamp_min(1.0))
        emb = F.embedding(ids, embed_w)
        s0 = rms_norm_f32(emb, embed_norm_w, eps)
        stack = torch.zeros((6, T, H), dtype=torch.float32, device=DEVICE)
        stack[0].copy_(s0)
        states.append({
            "T": T,
            "tau": tau,
            "stack": stack,
            "num_blocks": 0,
            "inputs": None,
            "bank": None,
            "prelude_blocks": None,
            "prelude_partial": None,
            "prelude_dests": None,
        })

    del embed_w

    visits = [(i, 0) for i in range(core_start)]
    visits += [(i, p) for p in range(num_passes) for i in range(core_start, core_end)]
    visits += [(i, 0) for i in range(core_end, num_layers)]

    def lin(x: torch.Tensor, w: torch.Tensor) -> torch.Tensor:
        if fp16_compute:
            return torch.mm(x.half(), w.half().t(), out_dtype=torch.float32)
        return torch.mm(x.float(), w.float().t())

    for visit, (i, pass_idx) in enumerate(visits):
        is_local = i in local_ids
        looped = pass_idx > 0
        pfx = f"model.llm.layers.{i}"

        # Load this layer's weights ONCE for all B prompts!
        if is_local:
            an_w = ws.get(f"{pfx}.attn_norm.weight").view(1, H)
        else:
            an_w = torch.stack([
                ws.get(f"{pfx}.q_input_norm.weight"),
                ws.get(f"{pfx}.k_input_norm.weight"),
                ws.get(f"{pfx}.v_input_norm.weight"),
            ], dim=0)
        mn_w = ws.get(f"{pfx}.mlp_norm.weight").view(1, H)

        wq = ws.get(f"{pfx}.attn.wq_du.weight")
        wr = ws.get(f"{pfx}.attn.wr_du.weight")
        wg = ws.get(f"{pfx}.attn.gate_attn.weight")
        wsink = ws.get(f"{pfx}.attn.attn_sink_proj.weight")
        wk = ws.get(f"{pfx}.attn.wk_dv.weight")
        wv = ws.get(f"{pfx}.attn.wv_dv.weight")
        wo = ws.get(f"{pfx}.attn.wo_ud.weight")
        q_scale = ws.get(f"{pfx}.attn.q_l2_clip.scale").view(n_heads, hd)
        r_scale = ws.get(f"{pfx}.attn.rel_l2_clip.scale").view(n_heads, d_rel)
        rel_proj = ws.get(f"{pfx}.attn.rel_logits_proj.proj")  # [d_rel, rel_extent]
        if is_local:
            k_sw = ws.get(f"{pfx}.attn.k_sconv.weight")
            v_sw = ws.get(f"{pfx}.attn.v_sconv.weight")
            k_wp = v_wp = None
        else:
            k_sw = ws.get(f"{pfx}.attn.k_sconv.static_w")
            v_sw = ws.get(f"{pfx}.attn.v_sconv.static_w")
            k_wp = ws.get(f"{pfx}.attn.k_sconv.weight_proj")
            v_wp = ws.get(f"{pfx}.attn.v_sconv.weight_proj")
        attn_sw = ws.get(f"{pfx}.attn_sconv.weight")
        mlp_sw = ws.get(f"{pfx}.mlp_sconv.weight")

        if looped:
            c_down = torch.stack([ws.get(f"{pfx}.controllers.{s}.down_weight") for s in ("attn", "k", "v", "mlp")], 0)
            c_gain = torch.stack([ws.get(f"{pfx}.controllers.{s}.gain_weight") for s in ("attn", "k", "v", "mlp")], 0)
            c_fgt = torch.stack([ws.get(f"{pfx}.controllers.{s}.forget_weight") for s in ("attn", "k", "v", "mlp")], 0)
        else:
            c_down = c_gain = c_fgt = None

        gate_w = ws.get(f"{pfx}.mlp.gate.weight")
        gate_b = ws.get(f"{pfx}.mlp.gate.bias", torch.float32)

        is_nvfp4 = i < 20
        # Load raw packed expert weights from safetensors on CPU (only dequant active experts on GPU!)
        sf = ws.sf
        w13_slice = sf.get_slice(f"{pfx}.mlp.experts.w13_weight")
        s13_slice = sf.get_slice(f"{pfx}.mlp.experts.w13_weight_scale")
        w2_slice = sf.get_slice(f"{pfx}.mlp.experts.w2_weight")
        s2_slice = sf.get_slice(f"{pfx}.mlp.experts.w2_weight_scale")
        if is_nvfp4:
            g13_all = (sf.get_tensor(f"{pfx}.mlp.experts.w13_weight_amax").float()
                       / sf.get_tensor(f"{pfx}.mlp.experts.w13_weight_outer_scale_denominator").float())
            g2_all = (sf.get_tensor(f"{pfx}.mlp.experts.w2_weight_amax").float()
                      / sf.get_tensor(f"{pfx}.mlp.experts.w2_weight_outer_scale_denominator").float())

        # Determine next_query / next_norm_w
        if visit + 1 == len(visits):
            next_q = output_query
            next_nw = final_norm_w.view(1, H)
        else:
            ni, npass = visits[visit + 1]
            next_q = attn_queries[ni - 1]
            if npass:
                next_nw = None
            else:
                if ni in local_ids:
                    next_nw = ws.get(f"model.llm.layers.{ni}.attn_norm.weight").view(1, H)
                else:
                    next_nw = torch.stack([
                        ws.get(f"model.llm.layers.{ni}.q_input_norm.weight"),
                        ws.get(f"model.llm.layers.{ni}.k_input_norm.weight"),
                        ws.get(f"model.llm.layers.{ni}.v_input_norm.weight"),
                    ], dim=0)

        # First run attention & routing across all B prompts to find union of active experts!
        pre_mlp = []
        active_experts: set[int] = set()
        for st in states:
            T = st["T"]
            stack = st["stack"]
            nb = st["num_blocks"]
            inputs = st["inputs"]
            bank = st["bank"]

            if i == core_start and not looped:
                st["prelude_blocks"] = nb
                st["prelude_partial"] = stack[nb].clone()
            elif i == core_start:
                bank = stack[st["prelude_blocks"] + 1 : nb + 1].clone()
                st["bank"] = bank
                nb = st["prelude_blocks"]
                st["num_blocks"] = nb
                stack[nb].copy_(st["prelude_partial"])
                if st["prelude_dests"] is None:
                    st["prelude_dests"] = attn_res_f32(
                        stack[:nb], st["prelude_partial"], None, attn_queries[i - 1], None, 0.0, True
                    )
                inputs = st["prelude_dests"]

            partial = stack[nb]
            messages = None
            if looped:
                assert bank is not None and inputs is not None
                messages = attn_res_f32(bank[:1], bank[1], None, msg_queries[i - core_start], None, 0.0, True)
                dests = inputs.expand(3, -1, -1) if is_local else inputs
                nw = an_w.expand(3, -1) if is_local else an_w
                attn_in = []
                for s_idx in range(3):
                    d_norm = rms_norm_f32(dests[s_idx], None, 1e-6)
                    m_norm = rms_norm_f32(messages[s_idx], None, 1e-6)
                    pair = torch.cat([d_norm, m_norm], dim=-1)
                    hid = lin(pair, c_down[s_idx])
                    if fp16_compute:
                        hid = hid.half()
                    gain = torch.tanh(lin(hid, c_gain[s_idx]))
                    fgt = torch.tanh(lin(hid, c_fgt[s_idx]))
                    blended = (1.0 - fgt) * dests[s_idx] + gain * messages[s_idx]
                    attn_in.append(rms_norm_f32(blended, nw[s_idx], eps))
                x_q, x_k, x_v = attn_in[0], attn_in[1], attn_in[2]
            elif inputs is None:
                x_q = rms_norm_f32(partial, an_w[0], eps)
                x_k = x_v = x_q
            else:
                x_q = inputs[0]
                x_k = inputs[0] if is_local else inputs[1]
                x_v = inputs[0] if is_local else inputs[2]

            if fp16_compute:
                x_q, x_k, x_v = x_q.half(), x_k.half(), x_v.half()

            q = lin(x_q, wq).view(T, n_heads, hd)
            r = lin(x_q, wr).view(T, n_heads, d_rel)
            gate_a = lin(x_q, wg)  # [T, n_heads * hd]
            sinks = lin(x_q, wsink)  # [T, n_heads]
            k = lin(x_k, wk)
            v = lin(x_v, wv)

            if is_local:
                k = static_sconv_f32(k, k_sw)
                v = static_sconv_f32(v, v_sw)
            else:
                dk = lin(x_k, k_wp)
                dv = lin(x_v, v_wp)
                k = dynamic_sconv_f32(k, k_sw, dk, hd)
                v = dynamic_sconv_f32(v, v_sw, dv, hd)

            # L2 clip Q, R, K; RMSNorm V (no gamma)
            q_c = l2_clip_f32(q * q_scale.float().unsqueeze(0), qk_clip, eps)
            r_c = l2_clip_f32(r * r_scale.float().unsqueeze(0), rel_clip, eps)
            if not is_local:
                if fp16_compute:
                    q_c = q_c.half().float()
                    r_c = r_c.half().float()
                q_c = q_c * st["tau"][:, None, None]
                r_c = r_c * st["tau"][:, None, None]
            k_c = l2_clip_f32(k.view(T, n_kv, hd), qk_clip, eps)
            v_c = rms_norm_f32(v.view(T, n_kv, hd), None, eps)

            if fp8_kv:
                k_c = k_c.clamp(-448.0, 448.0).to(torch.float8_e4m3fn).float()
                v_c = v_c.clamp(-448.0, 448.0).to(torch.float8_e4m3fn).float()
            elif fp16_compute:
                k_c = k_c.half().float()
                v_c = v_c.half().float()

            if fp16_compute:
                q_c = q_c.half().float()
                r_c = r_c.half().float()

            # Exact causal GQA attention + relative bias + gate_sink
            rep = n_heads // n_kv
            k_exp = k_c.repeat_interleave(rep, dim=1)  # [T, H, D]
            v_exp = v_c.repeat_interleave(rep, dim=1)
            scores = torch.einsum("thd,shd->hts", q_c, k_exp) * (hd ** -0.5)  # [H, T, T]
            # Relative bias: rel_all [T, H, rel_extent]
            rel_all = torch.einsum("thd,de->the", r_c, rel_proj.float())
            idx = torch.arange(T, device=DEVICE)
            dist = idx[:, None] - idx[None, :]  # [T, T]
            in_rel = (dist >= 0) & (dist < rel_extent)
            safe_dist = dist.clamp(0, rel_extent - 1)
            # Gather rel_bias[h, t, s] = rel_all[t, h, dist[t, s]]
            rel_b = rel_all.permute(1, 0, 2).gather(
                2, safe_dist.unsqueeze(0).expand(n_heads, T, T)
            )
            rel_b = torch.where(in_rel.unsqueeze(0), rel_b, torch.zeros_like(rel_b))
            scores = scores + rel_b
            causal_mask = dist >= 0
            if is_local:
                causal_mask = causal_mask & (dist < sw)
            scores = scores.masked_fill(~causal_mask.unsqueeze(0), float("-inf"))
            lse = torch.logsumexp(scores, dim=-1)  # [H, T]
            probs = torch.softmax(scores, dim=-1)  # [H, T, T]
            o = torch.einsum("hts,shd->thd", probs, v_exp)  # [T, H, D]
            o = o * torch.sigmoid(gate_a.view(T, n_heads, hd))
            o = o * torch.sigmoid(lse.t() - sinks).unsqueeze(-1)
            o_flat = o.reshape(T, n_heads * hd)
            if fp16_compute:
                o_flat = o_flat.half()

            attn_partial = lin(o_flat, wo)
            attn_out = static_sconv_f32(attn_partial, attn_sw)

            first = (i % block_size == 0)
            mlp_q = mlp_queries[i]
            mlp_nw = None if messages is not None else mn_w
            if first:
                mlp_in = attn_res_f32(stack[: nb + 1], attn_out, None, mlp_q, mlp_nw, eps, True)
            else:
                mlp_in = attn_res_f32(stack[:nb], partial, attn_out, mlp_q, mlp_nw, eps, True)
            if messages is not None:
                d_norm = rms_norm_f32(mlp_in[0], None, 1e-6)
                m_norm = rms_norm_f32(messages[3], None, 1e-6)
                pair = torch.cat([d_norm, m_norm], dim=-1)
                hid = lin(pair, c_down[3])
                if fp16_compute:
                    hid = hid.half()
                gain = torch.tanh(lin(hid, c_gain[3]))
                fgt = torch.tanh(lin(hid, c_fgt[3]))
                blended = (1.0 - fgt) * mlp_in[0] + gain * messages[3]
                mlp_x = rms_norm_f32(blended, mn_w[0], eps)
            else:
                mlp_x = mlp_in[0]

            if fp16_compute:
                mlp_x = mlp_x.half()

            residual = None if first else partial
            if residual is None:
                nb += 1
                st["num_blocks"] = nb

            # Route
            r_logits = torch.mm(mlp_x.half() if fp16_compute else mlp_x.float(),
                                gate_w.half().t() if fp16_compute else gate_w.float().t(),
                                out_dtype=torch.float32) if fp16_compute else torch.mm(mlp_x.float(), gate_w.float().t())
            sel = torch.sigmoid(r_logits) + gate_b.unsqueeze(0)
            top_idx = torch.topk(sel, k=topk, dim=-1).indices  # [T, 8]
            top_logits = r_logits.gather(1, top_idx)
            log_p = F.logsigmoid(top_logits)
            r_w = torch.softmax(log_p, dim=-1) * route_scale  # [T, 8]

            active_experts.update(top_idx.unique().tolist())
            pre_mlp.append((st, mlp_x, top_idx, r_w, attn_out, residual))

        # Execute active experts cleanly (dequant each active expert ONCE across all B prompts!)
        moe_outs = [torch.zeros((st["T"], H), dtype=torch.float32, device=DEVICE) for st in states]
        for e in sorted(active_experts):
            if is_nvfp4:
                we13 = dequant_nvfp4_expert(
                    w13_slice[e].to(DEVICE), s13_slice[e].to(DEVICE), float(g13_all[e].item())
                )
                we2 = dequant_nvfp4_expert(
                    w2_slice[e].to(DEVICE), s2_slice[e].to(DEVICE), float(g2_all[e].item())
                )
            else:
                we13 = dequant_mxfp8_expert(w13_slice[e].to(DEVICE), s13_slice[e].to(DEVICE))
                we2 = dequant_mxfp8_expert(w2_slice[e].to(DEVICE), s2_slice[e].to(DEVICE))
            if fp16_compute:
                we13_c, we2_c = we13.half(), we2.half()
            else:
                we13_c, we2_c = we13, we2

            for bi, (st, mlp_x, top_idx, r_w, _, _) in enumerate(pre_mlp):
                tok_pos, slot_pos = torch.where(top_idx == e)
                if tok_pos.numel() == 0:
                    continue
                xe = mlp_x[tok_pos]
                if fp16_compute:
                    gu = torch.mm(xe.half(), we13_c.t(), out_dtype=torch.float32)
                else:
                    gu = torch.mm(xe.float(), we13_c.t())
                g_raw = gu[:, 0::2]
                u_raw = gu[:, 1::2]
                sig = torch.sigmoid(g_raw)
                g_c = gate_cap * torch.tanh(g_raw / gate_cap)
                u_c = up_cap * torch.tanh(u_raw / up_cap)
                act = (g_c * sig) * u_c * r_w[tok_pos, slot_pos].unsqueeze(-1)
                if fp16_compute:
                    dn = torch.mm(act.half(), we2_c.t(), out_dtype=torch.float32)
                else:
                    dn = torch.mm(act.float(), we2_c.t())
                moe_outs[bi].index_add_(0, tok_pos, dn)

        for bi, (st, _, _, _, attn_out, residual) in enumerate(pre_mlp):
            nb = st["num_blocks"]
            stack = st["stack"]
            y_conv = static_sconv_f32(moe_outs[bi], mlp_sw)
            acc = attn_out if residual is None else (residual + attn_out)
            stack[nb].copy_(acc + y_conv)
            st["inputs"] = attn_res_f32(stack[:nb], stack[nb], None, next_q, next_nw, eps, True)

    # Final LM head -> FP32 logits + softcap(30.0)
    lm_w = ws.get("model.llm.unembed.weight")
    logits_list = []
    for st in states:
        x_final = st["inputs"][0]
        if fp16_compute:
            logits = torch.mm(x_final.half(), lm_w.half().t(), out_dtype=torch.float32)
        else:
            logits = torch.mm(x_final.float(), lm_w.float().t())
        logits = logits[:, :unpadded_vocab]
        logits = softcap * torch.tanh(logits / softcap)
        logits_list.append(logits)
    return logits_list


def eval_vs_oracle(
    name: str,
    oracle_logits: list[torch.Tensor],
    cand_logits: list[torch.Tensor],
    input_ids_list: list[torch.Tensor],
) -> dict[str, float]:
    cos_all, kl_all, match_all = [], [], []
    nll_ora_all, nll_cand_all = [], []
    for lo, lc, ids in zip(oracle_logits, cand_logits, input_ids_list):
        cos = F.cosine_similarity(lo, lc, dim=-1)
        p_o = torch.softmax(lo, dim=-1)
        lp_o = torch.log_softmax(lo, dim=-1)
        lp_c = torch.log_softmax(lc, dim=-1)
        kl = (p_o * (lp_o - lp_c)).sum(dim=-1)
        match = (lo.argmax(dim=-1) == lc.argmax(dim=-1)).float()
        cos_all.append(cos)
        kl_all.append(kl)
        match_all.append(match)
        # Teacher-forced next-token NLL on prompt tokens [0..T-2] -> [1..T-1]
        tgt = ids[1:]
        nll_ora_all.append(-lp_o[:-1].gather(1, tgt[:, None]).squeeze(1))
        nll_cand_all.append(-lp_c[:-1].gather(1, tgt[:, None]).squeeze(1))

    cos_cat = torch.cat(cos_all)
    kl_cat = torch.cat(kl_all)
    match_cat = torch.cat(match_all)
    dnll = (torch.cat(nll_cand_all) - torch.cat(nll_ora_all)).mean().item()
    res = {
        "name": name,
        "n_pos": int(cos_cat.numel()),
        "cos_mean": float(cos_cat.mean().item()),
        "cos_min": float(cos_cat.min().item()),
        "kl_mean": float(kl_cat.mean().item()),
        "kl_p95": float(torch.quantile(kl_cat, 0.95).item()),
        "dnll": float(dnll),
        "top1_match_pct": float(match_cat.mean().item() * 100.0),
    }
    print(
        f"  {name:34s} | cos={res['cos_mean']:.6f} (min {res['cos_min']:.5f}) | "
        f"KL={res['kl_mean']:.5f} (p95 {res['kl_p95']:.4f}) | "
        f"dNLL={res['dnll']:+.5f} | top1={res['top1_match_pct']:5.2f}%"
    )
    return res


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model-dir", required=True, help="Path to Inkling-2-Mini checkpoint")
    ap.add_argument("--fp8-dir", default="./fp8_dense", help="Directory with offline FP8 safetensors")
    args = ap.parse_args()

    model_dir = Path(args.model_dir)
    fp8_dir = Path(args.fp8_dir)
    with open(model_dir / "config.json") as f:
        cfg = json.load(f)["text_config"]
    tok = AutoTokenizer.from_pretrained(str(model_dir), trust_remote_code=True)
    input_ids_list = [
        torch.tensor(tok.encode(text), dtype=torch.long, device=DEVICE) for _, text in PROMPTS
    ]
    total_pos = sum(x.numel() for x in input_ids_list)
    print(f"Evaluating 48-visit Inkling-2-Mini real-weights oracle across {len(PROMPTS)} prompts ({total_pos} positions):")
    for (tag, _), ids in zip(PROMPTS, input_ids_list):
        print(f"  prompt[{tag}]: {ids.numel()} tokens")

    t0 = time.time()
    print("\n[1/6] Running exact FP32 oracle (FP32 dense + FP32 KV)...")
    ws_ora = WeightStore(None, set(), torch.float32, model_dir=model_dir)
    ora_logits = run_forward(input_ids_list, cfg, ws_ora, fp8_kv=False, fp16_compute=False)
    print(f"  done in {time.time() - t0:.1f}s")

    configs = [
        ("FP16 Baseline (FP8 KV)", None, set()),
        ("Tier 1: FP8 attn (absmax)", fp8_dir / "inkling2_fp8_dense_absmax.safetensors", {"attn"}),
        ("Tier 1: FP8 attn (mse)", fp8_dir / "inkling2_fp8_dense_mse.safetensors", {"attn"}),
        ("Tier 2: FP8 attn+lm_head (mse)", fp8_dir / "inkling2_fp8_dense_mse.safetensors", {"attn", "lm_head"}),
        ("Tier 3: FP8 attn+lm+ctrl (mse)", fp8_dir / "inkling2_fp8_dense_mse.safetensors", {"attn", "lm_head", "controllers"}),
    ]

    results = []
    print("\n=== 48-Visit Real-Weights Quality vs Exact FP32 Oracle ===")
    for _, (label, path, tiers) in enumerate(configs, 2):
        ts = time.time()
        ws = WeightStore(path, tiers, torch.float16, model_dir=model_dir)
        cand = run_forward(input_ids_list, cfg, ws, fp8_kv=True, fp16_compute=True)
        r = eval_vs_oracle(label, ora_logits, cand, input_ids_list)
        r["elapsed_s"] = round(time.time() - ts, 1)
        results.append(r)

    out_json = fp8_dir / "oracle_eval_results.json"
    out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(out_json, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nSaved oracle results to {out_json} (total {time.time() - t0:.1f}s)")


if __name__ == "__main__":
    main()
